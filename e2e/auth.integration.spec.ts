import { expect, test } from '@playwright/test'

test('real local registration, signed email verification, and browser sign-in work together', async ({ page }) => {
  test.setTimeout(180_000)
  const expectBackend = expect.configure({ timeout: 30_000 })
  const unique = `${Date.now()}-${Math.random().toString(36).slice(2, 9)}`
  const email = `browser-${unique}@example.test`
  const updatedEmail = `browser-updated-${unique}@example.test`
  const updatedPassword = 'ProfileUpdatedPass789'
  const organization = `Browser Test School ${unique}`
  const password = 'LocalIntegrationPass123'

  await page.goto('/register')
  await page.getByRole('textbox', { name: 'Full name' }).fill('E2E Browser Tester')
  await page.getByRole('textbox', { name: 'Email address' }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('textbox', { name: 'Organization name' }).fill(organization)
  await page.getByLabel('Organization type').selectOption('school')
  await page.getByRole('textbox', { name: 'Confirm password' }).fill(password)
  await page.getByRole('button', { name: 'Create account' }).click()

  await expectBackend(page.getByRole('heading', { name: 'You’re all set.' })).toBeVisible()
  const verifyButton = page.getByRole('button', { name: /Verify email to unlock sign-in/ })
  await expectBackend(verifyButton).toBeVisible()
  await expectBackend(page.getByText(/No inbox is needed for this local development link/)).toBeVisible()
  await verifyButton.click()
  await expectBackend(page.getByRole('status')).toContainText('Email verified. You can log in now.')

  await page.getByRole('link', { name: 'Log in', exact: true }).click()
  await page.getByRole('textbox', { name: 'Email address' }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Log in' }).click()

  await expectBackend(page).toHaveURL(/\/select-organization$/)
  await expectBackend(page.getByRole('heading', { name: 'Choose your workspace' })).toBeVisible()
  await expectBackend(page.getByRole('button', { name: new RegExp(organization) })).toBeVisible()
  await page.getByRole('button', { name: new RegExp(organization) }).click()
  await expectBackend(page).toHaveURL(/\/workspace\/admin$/)

  await page.goto('/forgot-password')
  await page.getByRole('textbox', { name: 'Email address' }).fill(email)
  await page.getByRole('button', { name: 'Send reset link' }).click()
  await expectBackend(page.getByText(/Your local password reset link is ready/)).toBeVisible()
  const resetLink = page.getByRole('link', { name: 'Reset your password' })
  await expectBackend(resetLink).toHaveAttribute('href', /\/reset-password\?/)
  const resetHref = await resetLink.getAttribute('href')
  if (!resetHref) throw new Error('The local password reset link is missing its destination.')
  const resetUrl = new URL(resetHref, page.url())
  expect(resetUrl.origin).toBe(new URL(page.url()).origin)
  expect(resetUrl.searchParams.get('email')).toBe(email)
  await resetLink.click()
  await expectBackend(page).toHaveURL(/\/reset-password\?/)
  await expectBackend(page.getByRole('textbox', { name: 'Email address' })).toHaveValue(email)
  await page.getByLabel('New password', { exact: true }).fill('ResetIntegrationPass456')
  await page.getByRole('textbox', { name: 'Confirm password' }).fill('ResetIntegrationPass456')
  await page.getByRole('button', { name: 'Reset password' }).click()
  await expectBackend(page.getByText('Your password has been updated. You can now sign in.')).toBeVisible()
  expect(await page.evaluate(async () => (await fetch('/api/v1/me', { credentials: 'include', headers: { Accept: 'application/json' } })).status)).toBe(401)

  await page.getByRole('link', { name: 'Back to log in' }).click()
  await page.getByRole('textbox', { name: 'Email address' }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill('ResetIntegrationPass456')
  await page.getByRole('button', { name: 'Log in' }).click()
  await expectBackend(page).toHaveURL(/\/select-organization$/)
  const workspaceChoice = page.getByRole('button', { name: new RegExp(organization) })
  await expectBackend(workspaceChoice).toBeVisible()
  await workspaceChoice.click()
  await expectBackend(page).toHaveURL(/\/workspace\/admin$/)
  await expectBackend(page.getByText('CONNECTED ACCOUNT · WORKSPACE DATA')).toBeVisible()

  await page.getByRole('button', { name: 'Invitations', exact: true }).click()
  await page.getByRole('tab', { name: 'Members & roles' }).click()
  await expectBackend(page.getByRole('heading', { name: 'Members and roles' })).toBeVisible()
  await expectBackend(page.getByRole('row', { name: new RegExp(email) })).toBeVisible()
  await expectBackend(page.getByRole('button', { name: 'Your account' })).toBeDisabled()

  await page.getByRole('button', { name: 'Preferences', exact: true }).click()
  await expectBackend(page.getByRole('heading', { name: 'Preferences', exact: true })).toBeVisible()
  await expectBackend(page.getByRole('heading', { name: 'Notification preferences' })).toBeVisible()
  await expectBackend(page.getByText(/Email delivery is disabled until/)).toBeVisible()
  const announcements = page.locator('.notification-preference-row').first().locator('input')
  await expectBackend(announcements).toBeChecked()
  await announcements.uncheck()
  await expectBackend(page.getByText('Preferences saved.')).toBeVisible()
  await page.getByRole('button', { name: 'Overview', exact: true }).click()
  await page.getByRole('button', { name: 'Preferences', exact: true }).click()
  await expectBackend(page.locator('.notification-preference-row').first().locator('input')).not.toBeChecked()

  await page.getByRole('button', { name: 'Account profile', exact: true }).click()
  await expectBackend(page.getByRole('heading', { name: 'Account profile', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.getByRole('textbox', { name: 'Full name' }).fill('E2E Profile Updated')
  await page.getByRole('textbox', { name: 'Email address' }).fill(updatedEmail)
  await page.getByLabel('Current password').fill('ResetIntegrationPass456')
  await page.getByRole('textbox', { name: 'New password (optional)' }).fill(updatedPassword)
  await page.getByLabel('Confirm new password').fill(updatedPassword)
  await page.getByRole('button', { name: 'Save account details' }).click()
  await expectBackend(page.getByText(/Your email was updated/)).toBeVisible()
  const profileVerificationTab = page.context().waitForEvent('page')
  await page.getByRole('link', { name: 'Verify email address', exact: true }).click()
  const verifiedProfilePage = await profileVerificationTab
  await expectBackend(verifiedProfilePage.locator('body')).toContainText('Email address verified. You can now sign in.')
  await page.reload()
  await expectBackend(page.getByRole('heading', { name: 'Choose your workspace' })).toBeVisible()
  await page.getByRole('button', { name: new RegExp(organization) }).click()
  await expectBackend(page).toHaveURL(/\/workspace\/admin$/)
  await expectBackend(page.getByText(updatedEmail)).toBeVisible()
  await expectBackend(page.getByRole('heading', { name: 'Welcome, E2E Profile Updated' })).toBeVisible()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expectBackend(page).toHaveURL(/\/login$/)
  await page.getByRole('textbox', { name: 'Email address' }).fill(updatedEmail)
  await page.getByLabel('Password', { exact: true }).fill(updatedPassword)
  await page.getByRole('button', { name: 'Log in' }).click()
  await expectBackend(page).toHaveURL(/\/select-organization$/)
  await page.getByRole('button', { name: new RegExp(organization) }).click()
  await expectBackend(page.getByRole('heading', { name: 'Welcome, E2E Profile Updated' })).toBeVisible()
})
